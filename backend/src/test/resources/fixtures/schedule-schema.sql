-- H2-only disposable fixture for doctor_schedules. Not a Flyway migration; never packaged in the boot JAR.
CREATE TABLE doctor_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES doctors(id),
    work_date DATE NOT NULL,
    start_at_utc TIMESTAMP(6) NOT NULL,
    end_at_utc TIMESTAMP(6) NOT NULL,
    slot_minutes SMALLINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_doctor_schedules_id_doctor UNIQUE (id, doctor_id)
);
