CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT NOT NULL REFERENCES users(id),
    appointment_id BIGINT NOT NULL REFERENCES appointments(id),
    event_key VARCHAR(128) NOT NULL,
    event_type VARCHAR(32) NOT NULL,
    title VARCHAR(160) NOT NULL,
    body VARCHAR(500),
    created_at TIMESTAMP(6) NOT NULL,
    read_at TIMESTAMP(6),
    CONSTRAINT uk_notifications_recipient_event UNIQUE(recipient_user_id, event_key),
    CONSTRAINT chk_notifications_type CHECK (event_type IN (
      'APPOINTMENT_CREATED','APPOINTMENT_RESCHEDULED','APPOINTMENT_CANCELLED','APPOINTMENT_CONFIRMED')),
    CONSTRAINT chk_notifications_key CHECK (CHAR_LENGTH(TRIM(event_key)) > 0 AND event_key = TRIM(event_key)),
    CONSTRAINT chk_notifications_title CHECK (CHAR_LENGTH(TRIM(title)) > 0),
    CONSTRAINT chk_notifications_read CHECK (read_at IS NULL OR read_at >= created_at)
);
CREATE INDEX IF NOT EXISTS ix_notifications_owner_created ON notifications(recipient_user_id, created_at, id);
CREATE INDEX IF NOT EXISTS ix_notifications_appointment ON notifications(appointment_id);
