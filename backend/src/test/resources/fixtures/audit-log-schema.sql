CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NULL REFERENCES users(id),
    actor_role VARCHAR(32) NOT NULL,
    action VARCHAR(64) NOT NULL,
    entity_type VARCHAR(64) NOT NULL,
    entity_id BIGINT NULL,
    result VARCHAR(16) NOT NULL,
    event_key VARCHAR(128) NULL,
    correlation_id VARCHAR(64) NULL,
    metadata VARCHAR(500) NULL,
    occurred_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_audit_logs_event_key UNIQUE (event_key),
    CONSTRAINT chk_audit_logs_actor_role CHECK (actor_role IN ('ADMIN', 'DOCTOR', 'RECEPTIONIST', 'PATIENT', 'SYSTEM')),
    CONSTRAINT chk_audit_logs_result CHECK (result IN ('SUCCESS', 'DENIED', 'FAILED')),
    CONSTRAINT chk_audit_logs_action CHECK (CHAR_LENGTH(TRIM(action)) > 0 AND action = TRIM(action)),
    CONSTRAINT chk_audit_logs_entity_type CHECK (CHAR_LENGTH(TRIM(entity_type)) > 0 AND entity_type = TRIM(entity_type))
);
CREATE INDEX IF NOT EXISTS ix_audit_logs_occurred_id ON audit_logs(occurred_at, id);
CREATE INDEX IF NOT EXISTS ix_audit_logs_actor_occurred_id ON audit_logs(actor_user_id, occurred_at, id);
CREATE INDEX IF NOT EXISTS ix_audit_logs_action_occurred_id ON audit_logs(action, occurred_at, id);
CREATE INDEX IF NOT EXISTS ix_audit_logs_entity ON audit_logs(entity_type, entity_id);
