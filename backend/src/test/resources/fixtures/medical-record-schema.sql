-- H2 test fixture for the QA-owned V9 migration.
CREATE TABLE IF NOT EXISTS medical_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments(id),
    symptoms TEXT,
    diagnosis TEXT,
    notes TEXT,
    conclusion TEXT,
    created_by BIGINT NOT NULL REFERENCES users(id),
    completed_by BIGINT REFERENCES users(id),
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CHECK ((completed_at IS NULL AND completed_by IS NULL)
        OR (completed_at IS NOT NULL AND completed_by IS NOT NULL AND completed_at >= created_at))
);
