package com.clinicmanagement.dto;

import com.clinicmanagement.entity.Appointment;
import java.time.Instant;

public record AppointmentResponse(
        String id,
        String appointmentCode,
        String patientId,
        String patientCode,
        String patientFullName,
        String patientPhone,
        String doctorId,
        String doctorCode,
        String doctorFullName,
        String specialtyName,
        String scheduleId,
        Instant startAt,
        Instant endAt,
        String status,
        String reason,
        Instant cancelledAt,
        String cancelledBy,
        String cancellationReason,
        Instant rescheduledAt,
        String rescheduledBy,
        String previousScheduleId,
        Instant previousStartAt,
        Instant confirmedAt,
        String confirmedBy,
        Instant checkedInAt,
        String checkedInBy,
        Instant noShowAt,
        String noShowBy,
        String createdBy,
        Long version,
        Instant createdAt,
        Instant updatedAt
) {
    public static AppointmentResponse from(Appointment a) {
        return new AppointmentResponse(
                a.getId().toString(),
                a.getAppointmentCode(),
                a.getPatient().getId().toString(),
                a.getPatient().getPatientCode(),
                a.getPatient().getFullName(),
                a.getPatient().getPhone(),
                a.getDoctor().getId().toString(),
                a.getDoctor().getDoctorCode(),
                a.getDoctor().getUser().getFullName(),
                a.getDoctor().getSpecialty() != null ? a.getDoctor().getSpecialty().getName() : null,
                a.getSchedule().getId().toString(),
                a.getStartAt(),
                a.getEndAt(),
                a.getStatus().name(),
                a.getReason(),
                a.getCancelledAt(),
                a.getCancelledBy() != null ? a.getCancelledBy().getId().toString() : null,
                a.getCancellationReason(),
                a.getRescheduledAt(),
                a.getRescheduledBy() != null ? a.getRescheduledBy().getId().toString() : null,
                a.getPreviousSchedule() != null ? a.getPreviousSchedule().getId().toString() : null,
                a.getPreviousStartAtUtc(),
                a.getConfirmedAt(),
                a.getConfirmedBy() != null ? a.getConfirmedBy().getId().toString() : null,
                a.getCheckedInAt(),
                a.getCheckedInBy() != null ? a.getCheckedInBy().getId().toString() : null,
                a.getNoShowAt(),
                a.getNoShowBy() != null ? a.getNoShowBy().getId().toString() : null,
                a.getCreatedBy().getId().toString(),
                a.getVersion(),
                a.getCreatedAt(),
                a.getUpdatedAt()
        );
    }
}
